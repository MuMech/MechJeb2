using MechJebLib.Primitives;
using MechJebLib.Utils;
using static MechJebLib.Utils.Statics;
using static System.Math;

/*
 * Russell's vercosine algorithm for solving Lambert's problem.
 *
 * Ported to C# from Lambert.jl (MIT License), src/russell_solver.jl
 * (commit e05ff7e573902ad4dd7b995655c367cb6dd6a9ff), which itself implements:
 *
 *   Russell, R. P. "On the Solution to Every Lambert Problem." Celestial Mechanics
 *   and Dynamical Astronomy 131, Article 50 (2019).
 *
 *   Russell, R. P. "Complete Lambert Solver Including Second-Order Sensitivities."
 *   Journal of Guidance, Control, and Dynamics 45.2 (2022): 196-212.
 *
 * Russell's ivLam was only used to identify constants and as a numerical source of
 * truth.  The following changes were made to the Lambert.jl algorithm:
 *
 * - The initial guess is interpolated like ivLam, using the variable transforms and
 *   binary tree polynomial interpolation published in Russell (2022), Section II.C-D (see
 *   RussellGuess).  The interpolation tables are generated by Tools/RussellTableGenerator
 *   from our own solutions of Lambert's equation, not taken from ivLam.  Unlike ivLam the
 *   minimum multi-rev time of flight is solved for instead of interpolated, since it is
 *   needed for bracketing (see below), with a Newton iteration seeded from an interpolation
 *   table for k_bottom.
 * - The convergence test is only applied after a full third order correction, like
 *   ivLam.  Lambert.jl applies it after safeguarded steps where the third order term
 *   is zeroed and declares convergence on the first iteration.
 * - For multi-rev, ivLam's small (2e-4) trust region on the step in k was tuned against
 *   the interpolated initial guess.  It is replaced by bracketing the requested branch
 *   of the time of flight curve at k_bottom, which is solved for with a safeguarded
 *   Newton iteration.
 * - The iteration also stops once the time of flight matches to within roundoff, which
 *   is needed for convergence very close to the double root at k_bottom.  Unlike ivLam
 *   this allows solutions arbitrarily close to the minimum multi-rev time of flight
 *   (Russell 2022 limits it to 1e-7 N above the minimum in units of S).
 * - The check that the iteration is not stuck on a steep cliff compares the residual to
 *   the time of flight, instead of max(1, time of flight).
 * - Fixed the k^7 coefficient in the series for W near k = 0 (Eq. 32 of Russell 2019), and
 *   the second and third derivatives in the series for large k (Algorithm 1 of Russell
 *   2019), which are wrong in Lambert.jl (ivLam has the same error in the series for the
 *   second derivative).
 * - The domain limits of Russell (2022) are the edges of the interpolation tables: |tau|
 *   within 1e-7 of sqrt(2)/2, which is the r1 == r2 singularity (a chord under about 1e-3 of
 *   the radius), or a zero-rev time of flight under 1e-3 times the parabolic time of flight.
 *   ivLam refuses to solve outside them, which here is optional (strict).  Otherwise zero-rev
 *   is solved outside them, with initial guesses from the asymptotic forms of the time of
 *   flight instead of the tables, bounds on p instead of k when iterating on p, and
 *   1 - sqrt(2) |tau| from the chord, since from tau it is lost to roundoff.  Close to
 *   theta = 2 pi on the long way k + sqrt(2) is also computed from p, and the velocities use
 *   the exact difference of the positions instead of the cancelling Lagrange coefficients.
 *   This solves close-in rendezvous arcs down to chords of about 1e-12 of the radius, and
 *   times of flight down to 1e-16 times the parabolic time of flight, in a few iterations.
 *   Multi-rev is always refused close to the r1 == r2 singularity, since its branches
 *   collapse into a band of width ~(1 - sqrt(2) |tau|) against k = +-sqrt(2), which the
 *   bracketing at k_bottom cannot resolve.  Inside the domain the results are unchanged.
 *   Only zero, negative and NaN times of flight and identical positions are always refused.
 * - Close to the half-rev, where the transfer plane is undefined or swamped by roundoff, the
 *   plane comes from the prograde/retrograde axis h, and the velocities come from a radial
 *   and transverse split of the Lagrange coefficients which is not singular.  Lambert.jl and
 *   ivLam instead offset g away from zero, which returns corrupt velocities.
 *
 * The first-order partial derivatives of the velocities with respect to the positions and
 * time of flight are computed by differentiating the converged root-solve of Lambert's
 * equation (Russell 2022, Eqs. 16 and 17), using derivatives of the vercosine
 * formulation (Russell 2019, Eqs. 25-29 and Algorithm 2) derived for this port.  For small p
 * the root-solve is differentiated with respect to p instead of k, like the iteration, since
 * dp from dk cancels to about EPS / p (which is O(1) below about 1e-7 times the parabolic time
 * of flight).
 */

