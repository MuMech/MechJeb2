namespace MechJebLib.Lambert
{
    /// <summary>
    ///     Solves Lambert's problem using Russell's vercosine formulation, iterating on k with
    ///     up to third order corrections.  The formulation has no singularities other than
    ///     r1 == r2 (and the undefined transfer plane of the exact half-rev, which needs h).
    /// </summary>
    public static class Russell
    {
        // Precision thresholds (ivLamThresh_*)
        private const double ZERO_BAND = 0.02; // ivLamThresh_zeroBand
        private const double PARABOLA_BAND = 0.02; // ivLamThresh_parabolaBand
        private const double BIG_K = 1000.0; // ivLamThresh_bigKiterate
        private const double LITTLE_P = 0.1; // ivLamThresh_littlePiterate
        private const double HUGE_TOF = 1e4; // ivLamThresh_TofByShugeBoundary
        private const double ALT_TAU_THRESH = 1e-2; // ivLamThresh_alternateTau
        private const double K_CLOSE_MSQRT2 = 1e-2; // ivLamThresh_kClosetoMsqrt2

        // Solver safeguards (ivLamSafegrd_*)
        private const double SERIES_CONVERGE = 1.01; // ivLamSafegrd_seriesConvergeThresh
        private const double SERIES_TAMP = 0.75; // ivLamSafegrd_seriesConvergeTamp
        private const double SERIES_TAMP_THRESH = 2e-7; // ivLamSafegrd_seriesConvergeTampThresh
        private const double BOTTOM_BUMP = 2e-4 * 0.5; // ivLamSafegrd_maxkStepMrev * ivLamSafegrd_botBumpMult
        private const double K_BUMP_INIT = 7e-7; // ivLamSafegrd_kBumpInit
        private const double K_BUMP_WEIGHT = 0.925; // ivLamSafegrd_kBumpWeightVio
        private const double K_MARGIN = 50.0 * EPS; // ivLamSafegrd_kmarginEpsMult

        // relative TOF residual which is considered roundoff (not from ivLam)
        private const double TOF_ROUNDOFF = 8.0 * EPS;

        // relative Newton step for kBottom after which it has converged (not from ivLam)
        private const double K_BOTTOM_STEP_TOL = 1e-10;

        // Domain limits (Russell 2022, Algorithms 1 and 3)
        private const double TAU_MARGIN = 1e-7; // minimum distance of |tau| from sqrt(2)/2, which is the r1 == r2 singularity
        private const double MIN_TOF_OVER_TP = 1e-3; // minimum zero-rev time of flight as a fraction of the parabolic time of flight

        // sqrt of the smallest normal double
        private const double SQRT_TINY = 1.4916681462400413e-154;

        // default angle from the half-rev inside which h defines the transfer plane, where the Lagrange coefficients miss r2
        // by about 1e-4 (relative) due to roundoff (not from ivLam)
        private const double HALF_REV_ANGLE = 1e-12;

        /// <summary>
        ///     Applies Russell's algorithm to solve Lambert's problem.
        /// </summary>
        /// <param name="mu">Gravitational parameter (mu)</param>
        /// <param name="r1">Initial position vector</param>
        /// <param name="r2">Final position vector</param>
        /// <param name="tof">Time of flight between both positions, must be positive (and with strict, at least 1e-3 times the parabolic time for nrev = 0)</param>
        /// <param name="direction">Which of the two Lambert arcs to solve for (see <see cref="TransferGeometry" />)</param>
        /// <param name="nrev">Number of full revolutions (+ long-period, - short-period for nrev != 0)</param>
        /// <param name="h">Axis to use for prograde/retrograde, and for the transfer plane close to a half-rev (does not need to be normalized)</param>
        /// <param name="numiter">Maximum number of iterations</param>
        /// <param name="halfRevAngle">
        ///     Angle in radians (at most about 0.1) from a half-rev inside which the transfer plane comes from h instead of
        ///     r1 x r2.  Inside it the solution misses r2 by up to about this angle times |r2|, when r2 is out of the plane of h.
        /// </param>
        /// <param name="strict">
        ///     Throw outside the domain of Russell (2022), like ivLam: positions within 1e-7 in tau of the r1 == r2 singularity
        ///     (a chord shorter than about 1e-3 of the radius), or a zero-rev time of flight under 1e-3 times the parabolic
        ///     time of flight.
        /// </param>
        /// <returns>The initial (v1) and final (v2) velocity vectors</returns>
        public static (V3 v1, V3 v2) Solve(double mu, V3 r1, V3 r2, double tof,
            TransferGeometry direction = TransferGeometry.ShortWay, int nrev = 0, V3? h = null, int numiter = 50,
            double halfRevAngle = HALF_REV_ANGLE, bool strict = false)
        {
            (V3 v1, V3 v2, _, _, _, _) = SolveWithState(mu, r1, r2, tof, direction, nrev, h, numiter, halfRevAngle, strict, out _);
            return (v1, v2);
        }

        /// <summary>
        ///     Applies Russell's algorithm to solve Lambert's problem, including the first-order partial derivatives of the
        ///     velocities with respect to the positions and time of flight.  The derivatives are singular at the minimum time
        ///     of flight for multi-rev transfers and at the half-rev, and lose precision close to them.  Inside halfRevAngle of
        ///     the half-rev this throws, since the transfer plane from h is discontinuous.
        /// </summary>
        /// <param name="mu">Gravitational parameter (mu)</param>
        /// <param name="r1">Initial position vector</param>
        /// <param name="r2">Final position vector</param>
        /// <param name="tof">Time of flight between both positions, must be positive (and with strict, at least 1e-3 times the parabolic time for nrev = 0)</param>
        /// <param name="direction">Which of the two Lambert arcs to solve for (see <see cref="TransferGeometry" />)</param>
        /// <param name="nrev">Number of full revolutions (+ long-period, - short-period for nrev != 0)</param>
        /// <param name="h">Axis to use for prograde/retrograde, and for the transfer plane close to a half-rev (does not need to be normalized)</param>
        /// <param name="numiter">Maximum number of iterations</param>
        /// <param name="halfRevAngle">Angle in radians (at most about 0.1) from a half-rev inside which the transfer plane comes from h</param>
        /// <param name="strict">Throw outside the domain of Russell (2022), like ivLam (see the other overload)</param>
        /// <returns>The initial (v1) and final (v2) velocity vectors, with derivatives along the dual parts of the inputs</returns>
        public static (DualV3 v1, DualV3 v2) Solve(double mu, DualV3 r1, DualV3 r2, Dual tof,
            TransferGeometry direction = TransferGeometry.ShortWay, int nrev = 0, V3? h = null, int numiter = 50,
            double halfRevAngle = HALF_REV_ANGLE, bool strict = false)
        {
            (V3 v1, V3 v2, double k, double p, double tau, bool halfRev) =
                SolveWithState(mu, r1.M, r2.M, tof.M, direction, nrev, h, numiter, halfRevAngle, strict, out _);

            // the transfer plane from h jumps with out of plane motion of r1 or r2
            if (halfRev)
                throw new ArgumentException("Russell's Lambert solver cannot compute derivatives close to a half-revolution transfer");

            // derivatives of the geometry: sigma = r1 + r2, S = sqrt(sigma^3 / mu) and tau = d sqrt(q) / sigma where
            // q = r1 r2 (1 + cos(theta)) = r1 r2 + r1vec . r2vec.
            double r1m = r1.M.magnitude;
            double r2m = r2.M.magnitude;
            double dr1m = V3.Dot(r1.M, r1.D) / r1m;
            double dr2m = V3.Dot(r2.M, r2.D) / r2m;
            double sigma = r1m + r2m;
            double dsigma = dr1m + dr2m;
            double S = sigma * Sqrt(sigma / mu);
            double dS = 1.5 * S * dsigma / sigma;
            double dq = dr1m * r2m + r1m * dr2m + V3.Dot(r1.D, r2.M) + V3.Dot(r1.M, r2.D);
            double dtau = dq / (2.0 * sigma * sigma * tau) - tau * dsigma / sigma;

            // close to theta = 2 pi on the long way W is from p, like in SolveWithState
            double oneMs2tau = nrev == 0 && tau < 0.0 && SQRT2 / 2 + tau < TAU_MARGIN
                ? OneMinusSqrt2AbsTau((r2.M - r1.M).magnitude, sigma, -tau)
                : 0.0;

            // implicit derivative of the converged k from Lambert's equation F = S L(k, tau) - tof = 0 (Russell 2022, Eq. 16).
            // For small p it is of p instead, like the iteration, since dp = -tau dk - k dtau cancels to about EPS / p
            // (L_p = -L_k / tau).
            (double L, double Lk, double Ltau, double LtauP) = TofPartials(k, p, tau, Abs(nrev), oneMs2tau);
            double dp;
            if (nrev == 0 && p < LITTLE_P)
            {
                dp = (S * LtauP * dtau + L * dS - tof.D) * tau / (S * Lk);
            }
            else
            {
                double dk = -(S * Ltau * dtau + L * dS - tof.D) / (S * Lk);
                dp = -tau * dk - k * dtau;
            }

            // derivatives of the velocities from the Lagrange coefficients (Russell 2019, Algorithm 2 and Russell 2022, Eq. 17)
            double a1 = sigma / r1m;
            double a2 = sigma / r2m;
            double da1 = (dsigma - a1 * dr1m) / r1m;
            double da2 = (dsigma - a2 * dr2m) / r2m;
            double f = 1.0 - p * a1;
            double gdot = 1.0 - p * a2;
            double df = -dp * a1 - p * da1;
            double dgdot = -dp * a2 - p * da2;
            double sqrtp = Sqrt(p);
            double g = S * tau * sqrtp;
            double dg = (dS * tau + S * dtau) * sqrtp + S * tau * dp / (2.0 * sqrtp);

            V3 dv1 = (r2.D - df * r1.M - f * r1.D - dg * v1) / g;
            V3 dv2 = (dgdot * r2.M + gdot * r2.D - r1.D - dg * v2) / g;

            return (new DualV3(v1, dv1), new DualV3(v2, dv2));
        }

        /// <summary>
        ///     Solves Lambert's problem, and returns the converged iteration variable k, p = 1 - k tau and tau along with
        ///     the velocities, whether the transfer plane came from h close to the half-rev, and the number of iterations taken.
        /// </summary>
        internal static (V3 v1, V3 v2, double k, double p, double tau, bool halfRev) SolveWithState(double mu, V3 r1, V3 r2, double tof,
            TransferGeometry direction, int nrev, V3? h, int numiter, double halfRevAngle, bool strict, out int iterations)
        {
            CheckDebug.PositiveFinite(mu);
            CheckDebug.PositiveFinite(tof);
            CheckDebug.NonZeroFinite(r1);
            CheckDebug.NonZeroFinite(r2);

            int nabs = Abs(nrev);
            bool zeroRev = nrev == 0;

            // Normalize to canonical units (mu = 1, |r1| = 1)
            double lRef = r1.magnitude;
            double tRef = Sqrt(lRef * lRef * lRef / mu);
            V3 r1Hat = r1 / lRef;
            V3 r2Hat = r2 / lRef;
            double r2Norm = r2Hat.magnitude;
            double tofHat = tof / tRef;

            // CheckDebug is compiled out of release builds, and without strict nothing else stops zero (teleportation),
            // negative or NaN times of flight
            if (!(tofHat > 0.0))
                throw new ArgumentException("Russell's Lambert solver requires a positive time of flight");

            // The transfer angle measured around h is in [0, pi] when (r1 x r2) . h >= 0, so prograde and retrograde just
            // pick the short way or long way (Russell 2019, Eq. 1).
            bool longWay = direction == TransferGeometry.LongWay || direction == TransferGeometry.Retrograde;
            if (direction == TransferGeometry.Prograde || direction == TransferGeometry.Retrograde)
            {
                if (h == null)
                    throw new ArgumentException("Russell's Lambert solver requires a normal vector for prograde or retrograde directions");
                longWay ^= V3.Dot(V3.Cross(r1Hat, r2Hat), h.Value) < 0;
            }

            // Geometry
            double r1pr2 = 1.0 + r2Norm;
            double r1r2 = r2Norm;
            double ctheta = Clamp(V3.Dot(r1Hat, r2Hat) / r2Norm, -1.0, 1.0);
            double onePctheta = ctheta + 1.0;
            double oneMctheta = 1.0 - ctheta;

            // Alternative form of tau for precision when theta is close to pi
            double abstau;
            V3 r1xr2 = V3.zero;
            double sthetar1r2 = 0.0;
            if (onePctheta < ALT_TAU_THRESH)
            {
                r1xr2 = V3.Cross(r1Hat, r2Hat);
                sthetar1r2 = r1xr2.magnitude;
                abstau = Sqrt(1.0 / (oneMctheta * r1r2)) / r1pr2 * sthetar1r2;
            }
            else
            {
                abstau = Sqrt(r1r2 * onePctheta) / r1pr2;
            }

            // Russell (2022) refuses geometries this close to the r1 == r2 singularity, which is the edge of the interpolation
            // tables.  For zero-rev the solution is still well conditioned in p (see the initial guess below), but the
            // multi-rev branches collapse into a band of width ~(1 - sqrt(2) |tau|) against k = +-sqrt(2), which the bracketing
            // on kBottom cannot resolve, so multi-rev always keeps the limit.
            bool tauTooClose = SQRT2 / 2 - abstau < TAU_MARGIN;
            if ((strict || !zeroRev) && tauTooClose)
                throw new ArgumentException("Russell's Lambert solver requires initial and final positions which are not too close to each other");

            // tau rounds to sqrt(2)/2 for chords below about 1e-8 of the radius, so only identical positions are refused
            if (r1Hat == r2Hat)
                throw new ArgumentException("Russell's Lambert solver requires initial and final positions which are distinct");

            // The Lambert equation is still solvable at the half-rev, but r1 x r2 does not define the transfer plane there and
            // roundoff swamps it close by, so within halfRevAngle (compared to sin(pi - theta)) h is used for the plane.  The
            // motion around h is the one that the direction picks when (r1 x r2) . h is not zero.  At the exact half-rev it is
            // counterclockwise around h for prograde and the short way, and clockwise for retrograde and the long way.
            bool halfRev = false;
            V3 t1Hat = V3.zero;
            if (h != null && onePctheta < ALT_TAU_THRESH && (sthetar1r2 < halfRevAngle * r2Norm || abstau < SQRT_TINY))
            {
                bool counterclockwise = longWay == V3.Dot(r1xr2, h.Value) < 0;
                t1Hat = V3.Cross(counterclockwise ? h.Value : -h.Value, r1Hat).safeNormalized;
                halfRev = t1Hat != V3.zero;
            }

            if (!halfRev && abstau < SQRT_TINY)
            {
                throw new ArgumentException(h == null
                    ? "Russell's Lambert solver requires a normal vector for an exact half-revolution transfer"
                    : "Russell's Lambert solver requires a normal vector which is not parallel to r1 for an exact half-revolution transfer");
            }

            // tau is proportional to cos(theta / 2), so the long way is the negative branch.  Everything downstream (the
            // initial guess, the bounds on k and the sign of g in the velocities) follows from the sign of tau.
            double tau = longWay ? -abstau : abstau;
            double tau2 = tau * tau;
            double tau3 = tau2 * tau;
            double S = r1pr2 * Sqrt(r1pr2);
            double tofbyS = tofHat / S;

            // Russell (2022) refuses zero-rev times of flight this small, which is the edge of the interpolation tables
            bool tofTooSmall = zeroRev && tofbyS < MIN_TOF_OVER_TP * Sqrt(1.0 - SQRT2 * tau) * (tau + SQRT2) / 3.0;
            if (strict && tofTooSmall)
                throw new ArgumentException("Russell's Lambert solver requires a time of flight of at least 1e-3 times the parabolic time of flight");

            // Outside the domain of the interpolation tables (only zero-rev gets here) the guess and the bounds on the
            // iteration are extended, and inside it they are unchanged.
            bool outsideDomain = tauTooClose || tofTooSmall;

            // 1 - sqrt(2) |tau| from the chord, since from tau it is lost to roundoff for chords under about 1e-8 of the radius
            double oneMs2tau = outsideDomain ? OneMinusSqrt2AbsTau((r2 - r1).magnitude / lRef, r1pr2, abstau) : 0.0;

            // Root-solve log(T)-log(T*) for very large time of flight
            bool hugeTof = tofbyS > HUGE_TOF;
            double logTofbyS = hugeTof ? Log(tofbyS) : 0.0;

            // Range of k, the multi-rev range is further bracketed to the requested branch
            double kLeft = -SQRT2 + K_MARGIN;
            double kRight;
            if (zeroRev && tau > 0.0)
                kRight = 1.0 / tau * (1.0 - K_MARGIN);
            else if (zeroRev)
                kRight = 1e90;
            else
                kRight = SQRT2 - K_MARGIN;

            // see LongWayNearSingularityGuess
            double pLongWay = tauTooClose && tau < 0.0 && tofbyS > 0.25 * PI ? LongWayNearSingularityGuess(oneMs2tau, tofbyS) : double.MaxValue;

            double k;
            double p = 0.0;
            bool guessP = false;
            if (zeroRev && outsideDomain && tau > 0.0 && tofbyS * tofbyS < LITTLE_P * tau2)
            {
                // Short way solutions with small p, which are all the fast ones and the ones close to the r1 == r2
                // singularity (where p ~ 1 - sqrt(2) tau unless the time of flight is huge).  TOF/S = sqrt(p) (tau + p W),
                // and p W is small compared to tau.  The guess is in p, since k = (1 - p) / tau is too close to 1 / tau to
                // resolve p.
                p = tofbyS * tofbyS / tau2;
                k = (1.0 - p) / tau;
                guessP = true;
            }
            else if (zeroRev && pLongWay < LITTLE_P)
            {
                // Long way solutions close to theta = 2 pi, which are within 1 - sqrt(2) |tau| of k = -sqrt(2) unless the
                // time of flight is short.  The guess is in p, since k does not resolve its distance from -sqrt(2).
                p = pLongWay;
                k = (1.0 - p) / tau;
                guessP = true;
            }
            else if (zeroRev && tofTooSmall && tau < 0.0)
            {
                // Fast long way hyperbolas, where tau + p W ~ 1/k so TOF/S ~ sqrt(1 - k tau) / k.  Newton steps from the edge
                // of the tables only grow k by about 2.5 times per iteration.
                double L2 = tofbyS * tofbyS;
                k = (-tau + Sqrt(tau2 + 4.0 * L2)) / (2.0 * L2);
            }
            else if (zeroRev)
            {
                k = RussellGuess.ZeroRev(tau, tofbyS);

                // defensive, the interpolation should always produce a finite guess (outside the domain the tables are
                // evaluated at their edges, and very close to the singularity 1 - sqrt(2) tau may round to zero)
                if (!IsFinite(k))
                    k = 0.0;
            }
            else
            {
                double x = RussellGuess.X(tau);
                double z = RussellGuess.Z(nabs);
                (double kBottom, double tofbySBottom) = MultiRevBottom(tau, nabs, RussellGuess.KBottom(tau, x, z, nabs), out _);

                if (tofbyS <= tofbySBottom)
                    throw new Exception("Russell's Lambert solver found no solution: time of flight is less than the minimum for this number of revolutions");

                k = RussellGuess.MultiRev(x, z, tofbyS - tofbySBottom, nrev, kBottom);

                if (nrev > 0)
                    kLeft = kBottom;
                else
                    kRight = kBottom;
            }

            // The multi-rev guess is always strictly on the requested branch, and can be accurate much closer to the far end
            // of the branch than K_BUMP_INIT, so it is only kept away from the double root at kBottom.  A guess in p is
            // already strictly inside 0 < p < LITTLE_P, and K_BUMP_INIT would keep it from p ~ 0.
            if (!guessP)
            {
                if (zeroRev)
                    k = Clamp(k, kLeft + K_BUMP_INIT, kRight - K_BUMP_INIT);
                else if (nrev > 0)
                    k = Clamp(k, kLeft + K_BUMP_INIT, kRight);
                else
                    k = Clamp(k, kLeft, kRight - K_BUMP_INIT);

                p = 1.0 - k * tau;
            }

            // iterate on p instead of k when p is small (only happens for zero-rev)
            bool iterateOnP = zeroRev && p < LITTLE_P;

            // Outside the domain, when iterating on p the bounds on k are applied to p (p > 0 for the short way, and
            // p > 1 - sqrt(2) |tau| for the long way), and the convergence test is relative to p, since p can be much smaller
            // than LITTLE_P.  For the short way kRight is K_MARGIN from p = 0, which keeps p from the solution for times of
            // flight under about 1e-7 S.  For the long way the solution is close to k = -sqrt(2), where k + sqrt(2) is
            // computed from p and 1 - sqrt(2) |tau| to keep the relative precision of W, instead of from k, which would leave
            // a relative error in the time of flight of EPS / (1 - sqrt(2) |tau|).  1 - sqrt(2) |tau| is from the chord, since
            // from tau it is lost to roundoff for chords under about 1e-8.
            bool pBounds = outsideDomain && iterateOnP;
            double pMin = tau < 0.0 ? oneMs2tau : 0.0;

            // for multi-rev, if the TOF curve slope says we are on the other branch then bump back towards the requested branch
            double signBump = zeroRev ? 0.0 : nrev > 0 ? BOTTOM_BUMP : -BOTTOM_BUMP;

            bool converged = false;
            iterations = 0;

            for (int iter = 0; iter < numiter; iter++)
            {
                iterations = iter + 1;

                double kLast = k;
                double pLast = p;

                bool hugeK = zeroRev && k > BIG_K;

                // relF0 is the TOF residual relative to the TOF (the log form is already relative)
                double F0, F1, F2, F3, relF0;

                if (hugeK)
                {
                    (F0, F1, F2, F3) = TofDerivsBigK(k, p, tau, tau2, tofbyS);
                    relF0 = F0 / tofbyS;
                }
                else
                {
                    double W0, W1, W2, W3;
                    if (pBounds && tau < 0.0)
                        (W0, W1, W2, W3) = GetWLongWay(p, oneMs2tau, abstau);
                    else
                        (W0, W1, W2, W3) = GetW(k, nabs);

                    (F0, F1, F2, F3) = TofDerivs(p, tau, tau2, tau3, tofbyS, logTofbyS, W0, W1, W2, W3, hugeTof);
                    relF0 = hugeTof ? F0 : F0 / tofbyS;
                }

                int info;
                double dv3 = 0.0;
                double compVal = 0.0;

                if (signBump * F1 < 0.0)
                {
                    k = kLast + signBump;
                    p = 1.0 - k * tau;
                    info = -1;
                }
                else if (iterateOnP)
                {
                    double dv1, dv2;
                    (info, dv1, dv2, dv3) = Correction(F0, F1 / -tau, F2 / tau2, F3 / -tau3);
                    p += dv1 + dv2 + dv3;
                    compVal = LITTLE_P;
                    k = (1.0 - p) / tau;
                }
                else
                {
                    double dv1, dv2;
                    (info, dv1, dv2, dv3) = Correction(F0, F1, F2, F3);
                    k += dv1 + dv2 + dv3;
                    compVal = k;
                    p = 1.0 - k * tau;
                }

                // steps which violate the bounds go most of the way to the bound from the last step
                if (pBounds && !(p > pMin))
                {
                    p = (1.0 - K_BUMP_WEIGHT) * pLast + K_BUMP_WEIGHT * pMin;
                    k = (1.0 - p) / tau;
                }
                else if (!(pBounds && tau < 0.0) && k < kLeft)
                {
                    k = (1.0 - K_BUMP_WEIGHT) * kLast + K_BUMP_WEIGHT * kLeft;
                    p = 1.0 - k * tau;
                }
                else if (!pBounds && k > kRight)
                {
                    k = (1.0 - K_BUMP_WEIGHT) * kLast + K_BUMP_WEIGHT * kRight;
                    p = 1.0 - k * tau;
                }

                if (F0 == 0.0)
                {
                    converged = true;
                    break;
                }

                // stop when the third order term of a full correction no longer changes the iteration variable, and
                // make sure we are not stuck on a steep cliff near a boundary.
                if (info == 0 && Abs(dv3) / (pBounds ? p : Max(SQRT_EPS, Abs(compVal))) < EPS && Abs(relF0) < 1.0)
                {
                    converged = true;
                    break;
                }

                // Near the double root at the bottom of a multi-rev TOF curve the roundoff in F0 is amplified by the
                // small slope and the corrections never become clean, so also stop at the last evaluated point once
                // its TOF matches to within roundoff.
                if (info != -1 && Abs(relF0) <= TOF_ROUNDOFF)
                {
                    k = kLast;
                    p = pLast;
                    converged = true;
                    break;
                }
            }

            if (!converged)
                throw new Exception("Russell's Lambert solver failed to converge");

            V3 v1, v2;

            if (halfRev)
            {
                // The Lagrange coefficients below are 0/0 at the exact half-rev and lose precision close to it.  Split into
                // radial and transverse parts they are not singular, in units where r1 = 1:
                //   v1 = ((tau (1 + r2) - k) r1hat + sqrt(2 r2) sin(theta / 2) t1hat) / sqrt((1 + r2) p)
                //   v2 = ((k - tau (1 + r2) / r2) u2hat + sqrt(2 / r2) sin(theta / 2) t2hat) / sqrt((1 + r2) p)
                // where t1hat and t2hat are the directions of motion, and u2hat is where the transfer angle in the plane of h
                // lands (which is r2hat when r2 is in that plane).
                double stheta = (tau < 0 ? -sthetar1r2 : sthetar1r2) / r2Norm;
                V3 u2Hat = ctheta * r1Hat + stheta * t1Hat;
                V3 t2Hat = ctheta * t1Hat - stheta * r1Hat;
                double sthetaHalf = Sqrt(0.5 * oneMctheta);
                double sqrtr1pr2p = Sqrt(r1pr2 * p);
                v1 = ((tau * r1pr2 - k) * r1Hat + Sqrt(2.0 * r2Norm) * sthetaHalf * t1Hat) / sqrtr1pr2p;
                v2 = ((k - tau * r1pr2 / r2Norm) * u2Hat + Sqrt(2.0 / r2Norm) * sthetaHalf * t2Hat) / sqrtr1pr2p;
            }
            else
            {
                // Reconstruct the velocities from the Lagrange coefficients
                double pr12 = p * r1pr2;
                double f = 1.0 - pr12;
                double g = S * tau * Sqrt(p);
                double gdot = 1.0 - pr12 / r2Norm;

                if (outsideDomain)
                {
                    // f and gdot are close to 1 when p is small, so r2Hat - f r1Hat cancels to about EPS / chord.  The
                    // difference of the positions is exact (Sterbenz), so it is used for the chord instead.
                    V3 dr = (r2 - r1) / lRef;
                    v1 = (dr + pr12 * r1Hat) / g;
                    v2 = (dr - pr12 / r2Norm * r2Hat) / g;
                }
                else
                {
                    v1 = (r2Hat - f * r1Hat) / g;
                    v2 = (gdot * r2Hat - r1Hat) / g;
                }
            }

            double vScale = lRef / tRef;

            return (v1 * vScale, v2 * vScale, k, p, tau, halfRev);
        }

        /// <summary>
        ///     The vercosine W(k) function and its first three derivatives with respect to k.  W(k) plays
        ///     the role of the Stumpff functions in the vercosine formulation.
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal static (double W, double dW1, double dW2, double dW3) GetW(double k, int nabs) => GetW(k, nabs, k + SQRT2, 2.0 - k * k);

        /// <summary>
        ///     1 - sqrt(2) |tau| = c^2 / (sigma^2 (1 + sqrt(2) |tau|)) from the chord c and sigma = r1 + r2 (in the same units),
        ///     which is precise close to the r1 == r2 singularity, unlike 1 - sqrt(2) |tau| from tau.
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static double OneMinusSqrt2AbsTau(double chord, double sigma, double abstau) =>
            chord * chord / (sigma * sigma * (1.0 + SQRT2 * abstau));

        /// <summary>
        ///     W(k) and its derivatives for zero-rev close to k = -sqrt(2) (the long way close to theta = 2 pi), from
        ///     k + sqrt(2) = (p - (1 - sqrt(2) |tau|)) / |tau|.  From k this loses its relative precision, which leaves a relative
        ///     error in W of about EPS / (1 - sqrt(2) |tau|).
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static (double W, double dW1, double dW2, double dW3) GetWLongWay(double p, double oneMs2tau, double abstau)
        {
            double kps2 = (p - oneMs2tau) / abstau;
            return GetW(kps2 - SQRT2, 0, kps2, (2.0 * SQRT2 - kps2) * kps2);
        }

        /// <summary>
        ///     W(k) and its derivatives, given kps2 = k + sqrt(2) and m = 2 - k^2, which lose precision close to k = -sqrt(2)
        ///     when computed from k.
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static (double W, double dW1, double dW2, double dW3) GetW(double k, int nabs, double kps2, double m)
        {
            double k2 = k * k;
            double nu = k - SQRT2;
            double twoPiN = TAU * nabs;

            // near the parabola, series in nu = k - sqrt(2)
            if (k2 > ZERO_BAND * ZERO_BAND && nabs == 0 && Abs(nu) < PARABOLA_BAND)
                return GetWParabola(nu);

            double onebym = 1.0 / m;
            double tnpp = twoPiN + PI;

            double W;
            if (k2 <= ZERO_BAND * ZERO_BAND)
            {
                // near zero, series in k for precision
                double k3 = k2 * k;
                double k4 = k2 * k2;
                double k5 = k4 * k;
                double k6 = k4 * k2;
                double k7 = k4 * k3;
                double k8 = k4 * k4;
                W = 0.3535533905932738 * tnpp - k + 0.2651650429449553 * tnpp * k2 - 2.0 / 3.0 * k3 +
                    0.1657281518405971 * tnpp * k4 - 0.4 * k5 + 0.09667475524034829 * tnpp * k6 -
                    8.0 / 35.0 * k7 + 0.05437954982269591 * tnpp * k8;
            }
            else if (m >= 0.0)
            {
                // ellipse (m is the same test as k2 <= 2, except when m is from kps2 and k rounds to -sqrt(2))
                double k2m1 = k2 - 1.0;
                if (k > 0.0)
                {
                    W = (twoPiN + Acos(k2m1)) * Sqrt(onebym * onebym * onebym) - k * onebym;
                }
                else
                {
                    if (kps2 < K_CLOSE_MSQRT2)
                    {
                        // series in k + sqrt(2) for smoothness near k = -sqrt(2)
                        double tNp = TAU + twoPiN;
                        double t1 = kps2 * kps2;
                        double t2 = Sqrt(kps2);
                        double t3 = t2 * t1;
                        double t9 = t1 * t1;
                        double t10 = t2 * t9;
                        W = 0.12110150049603174603174603174603e-7 / t3 * (
                            -0.38926398009946925989672338336519e8 * t3 -
                            0.16515072e8 * t2 * kps2 * t1 -
                            0.1976320e7 * t10 * (kps2 + 2.4532575164897006338798206469711) -
                            0.18246749067162621557658908595243e7 * t10 +
                            0.25959796716951899525909665607350e6 *
                            (t9 + 6.4646464646464646464646464646465 * t1 + 35.463203463203463203463203463203) *
                            tNp * t1 +
                            0.66750357442839860425810740303391e6 *
                            tNp * (t9 + 6.0952380952380952380952380952381 * t1 + 26.006349206349206349206349206349) *
                            kps2 - 645120.0 * t2 * kps2 * t9
                        );
                    }
                    else
                    {
                        W = (TAU + twoPiN - Acos(k2m1)) * Sqrt(onebym * onebym * onebym) - k * onebym;
                    }
                }
            }
            else
            {
                // hyperbola
                double k2m1 = k2 - 1.0;
                W = -Log(k2m1 + Sqrt(k2m1 * k2m1 - 1.0)) * Sqrt(-onebym * onebym * onebym) - k * onebym;
            }

            double t = 3.0 * W;
            double dW1 = (t * k - 2.0) * onebym;
            double dW2 = (5.0 * dW1 * k + t) * onebym;
            double dW3 = (7.0 * dW2 * k + 8.0 * dW1) * onebym;

            return (W, dW1, dW2, dW3);
        }

        /// <summary>
        ///     W(k) and its derivatives from the Taylor series near the parabola, where nu = k - sqrt(2).
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static (double W, double dW1, double dW2, double dW3) GetWParabola(double nu)
        {
            double nu2 = nu * nu;
            double nu3 = nu2 * nu;
            double nu4 = nu2 * nu2;
            double nu5 = nu4 * nu;
            double nu6 = nu4 * nu2;
            double nu7 = nu4 * nu3;
            double nu8 = nu4 * nu4;

            double W = 0.47140452079103168 - 0.2 * nu + 0.080812203564176860 * nu2 -
                0.031746031746031746 * nu3 + 0.012244273267299524 * nu4 - 0.0046620046620046620 * nu5 +
                0.0017581520588942907 * nu6 - 0.00065816536404771699 * nu7 +
                0.00024494378529487022 * nu8;

            double dW1 = -0.2 + 0.16162440712835372 * nu - 0.095238095238095238 * nu2 +
                0.048977093069198097 * nu3 - 0.023310023310023310 * nu4 +
                0.010548912353365744 * nu5 - 0.0046071575483340189 * nu6 +
                0.0019595502823589617 * nu7;

            double dW2 = 0.16162440712835372 - 0.19047619047619048 * nu + 0.14693127920759429 * nu2 -
                0.093240093240093240 * nu3 + 0.052744561766828720 * nu4 -
                0.027642945290004114 * nu5 + 0.013716851976512732 * nu6;

            double dW3 = -0.19047619047619048 + 0.29386255841518858 * nu - 0.27972027972027972 * nu2 +
                0.21097824706731488 * nu3 - 0.13821472645002057 * nu4 + 0.082301111859076392 * nu5;

            return (W, dW1, dW2, dW3);
        }

        /// <summary>
        ///     The normalized TOF/S residual and its derivatives with respect to k.  For very large TOF/S the
        ///     residual is log(TOF/S) - log(TOF*/S) to maintain precision.
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal static (double F0, double F1, double F2, double F3) TofDerivs(double p, double tau, double tau2, double tau3, double tofbyS,
            double logTofbyS, double W0, double W1, double W2, double W3, bool hugeTof)
        {
            double sqrtp = Sqrt(p);

            double leftSide = sqrtp * (p * W0 + tau);

            double t7 = p * p;
            double onebyrootp = 1.0 / sqrtp;
            double F1 = (-3.0 * p * tau * W0 + 2.0 * t7 * W1 - tau2) * onebyrootp * 0.5;

            double onebyp = onebyrootp * onebyrootp;
            double onebyp32 = onebyrootp * onebyp;
            double p3dw0 = 3.0 * p * W0;
            double t7tau = t7 * tau;
            double F2 = (p3dw0 * tau2 + 4.0 * t7 * p * W2 - 12.0 * t7tau * W1 - tau3) * onebyp32 * 0.25;

            double F3 = (p3dw0 * tau3 + 18.0 * t7 * tau2 * W1 - 36.0 * t7tau * p * W2 + 8.0 * t7 * t7 * W3 - 3.0 * tau2 * tau2) *
                onebyp32 * onebyp * 0.125;

            if (!hugeTof)
                return (leftSide - tofbyS, F1, F2, F3);

            double F0 = Log(leftSide) - logTofbyS;
            double t1 = 1.0 / leftSide;
            double t10 = F1;
            double t20 = F2;
            double t30 = F3;
            F1 = t10 * t1;
            double t4 = F1 * F1;
            F2 = t20 * t1 - t4;
            double t2 = t1 * t1;
            F3 = t30 * t1 - 3.0 * t20 * t10 * t2 + 2.0 * t4 * F1;

            return (F0, F1, F2, F3);
        }

        /// <summary>
        ///     Series expansion in 1/k of the TOF/S residual and its derivatives for very large k (extreme hyperbolas),
        ///     where tau + pW loses precision.  This is Algorithm 1 of Russell (2019).
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal static (double F0, double F1, double F2, double F3) TofDerivsBigK(double k, double p, double tau, double tau2, double tofbyS)
        {
            double ka = 1.0 / k;
            double ka2 = ka * ka;
            double ka3 = ka2 * ka;
            double ka4 = ka2 * ka2;
            double ka5 = ka4 * ka;
            double ka6 = ka3 * ka3;
            double ka7 = ka4 * ka3;
            double ka8 = ka4 * ka4;
            double lnka = Log(ka);
            double t1 = -LN2 + 2.0 * lnka + 2.0;
            double t2 = -3.0 * LN2 + 6.0 * lnka + 5.0;

            // truncated series for Z = tau + pW and its derivatives with respect to k
            double Z0 = t2 * ka5 - t2 * tau * ka4 + t1 * ka3 - t1 * tau * ka2 + ka;
            double Z1 = (-5.0 * t2 - 6.0) * ka6 + (4.0 * tau * t2 + 6.0 * tau) * ka5 + (-3.0 * t1 - 2.0) * ka4 + (2.0 * tau * t1 + 2.0 * tau) * ka3 - ka2;
            double Z2 = (30.0 * t2 + 66.0) * ka7 + (-20.0 * tau * t2 - 54.0 * tau) * ka6 + (12.0 * t1 + 14.0) * ka5 + (-6.0 * tau * t1 - 10.0 * tau) * ka4 +
                2.0 * ka3;
            double Z3 = (-210.0 * t2 - 642.0) * ka8 + (120.0 * tau * t2 + 444.0 * tau) * ka7 + (-60.0 * t1 - 94.0) * ka6 +
                (24.0 * tau * t1 + 52.0 * tau) * ka5 - 6.0 * ka4;

            double pr = Sqrt(p);
            double pr3 = pr * p;
            double pr5 = pr3 * p;

            double F0 = pr * Z0 - tofbyS;
            double F1 = -Z0 * tau / (2.0 * pr) + pr * Z1;
            double F2 = -Z0 * tau2 / (4.0 * pr3) - Z1 * tau / pr + pr * Z2;
            double F3 = -3.0 * Z0 * tau2 * tau / (8.0 * pr5) - 3.0 * Z1 * tau2 / (4.0 * pr3) - 3.0 * Z2 * tau / (2.0 * pr) + pr * Z3;

            return (F0, F1, F2, F3);
        }

        /// <summary>
        ///     The normalized time of flight L = T/S = sqrt(p) (tau + pW) and its partial derivatives with respect to k (at
        ///     fixed tau) and tau (at fixed k, and at fixed p), at the converged solution.
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static (double L, double Lk, double Ltau, double LtauP) TofPartials(double k, double p, double tau, int nabs, double oneMs2tau)
        {
            double sqrtp = Sqrt(p);
            double L, Lk, Ltau, LtauP;

            if (nabs == 0 && k > BIG_K)
            {
                // series in 1/k (Russell 2019, Algorithm 1), where L = sqrt(p) Z and dZ/dtau is from the same series
                (L, Lk, _, _) = TofDerivsBigK(k, p, tau, tau * tau, 0.0);
                double ka = 1.0 / k;
                double ka2 = ka * ka;
                double lnka = Log(ka);
                double t1 = -LN2 + 2.0 * lnka + 2.0;
                double t2 = -3.0 * LN2 + 6.0 * lnka + 5.0;
                double Ztau = -t2 * ka2 * ka2 - t1 * ka2;
                Ltau = -k * L / (2.0 * p) + sqrtp * Ztau;
                LtauP = Ltau - Lk * k / tau;
            }
            else
            {
                (double W0, double W1, _, _) = oneMs2tau > 0.0 ? GetWLongWay(p, oneMs2tau, -tau) : GetW(k, nabs);
                double Z = tau + p * W0;
                L = sqrtp * Z;
                Lk = (-3.0 * p * tau * W0 + 2.0 * p * p * W1 - tau * tau) / (2.0 * sqrtp);
                Ltau = -k * Z / (2.0 * sqrtp) + sqrtp * (1.0 - k * W0);

                // at fixed p, where k = (1 - p) / tau, which is Ltau - Lk k / tau without the cancellation of its 1 / sqrt(p) terms
                LtauP = sqrtp * (1.0 - p * W1 * k / tau);
            }

            return (L, Lk, Ltau, LtauP);
        }

        /// <summary>
        ///     The root-solve correction, split into its first, second and third order terms, with checks that the series
        ///     is converging.  Info is 0 for a full third order correction and nonzero when a safeguard truncated it.
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static (int info, double dv1, double dv2, double dv3) Correction(double F0, double F1, double F2, double F3)
        {
            double monebydf = -1.0 / F1;
            double dv1 = F0 * monebydf;

            double dvm = dv1 * monebydf;
            double dkA = dv1 * dvm;
            double dv2 = 0.5 * dkA * F2;

            double absdv1 = Abs(dv1);
            if (Abs(dv2) * SERIES_CONVERGE > absdv1)
            {
                // too steep for the higher order terms, take a slightly shortened Newton step
                if (absdv1 > SERIES_TAMP_THRESH)
                    dv1 *= SERIES_TAMP;
                return (2, dv1, 0.0, 0.0);
            }

            double dv3 = dkA * dv1 * F3 / 6.0 + dv2 * F2 * dvm;

            if (Abs(dv3) * SERIES_CONVERGE * SERIES_CONVERGE > absdv1)
                return (3, dv1, dv2, 0.0);

            return (0, dv1, dv2, dv3);
        }

        /// <summary>
        ///     Initial guess for p for zero-rev long way transfers close to the r1 == r2 singularity (theta close to 2 pi), with
        ///     TOF/S > pi / 4.  Close to k = -sqrt(2), m = 2 - k^2 ~ 4 (p - eps) where eps = 1 - sqrt(2) |tau|, and the leading
        ///     term of W is 2 pi / m^1.5, so TOF/S = sqrt(p) (tau + p W) ~ (pi / 4) (p / (p - eps))^1.5.  The guess is relatively
        ///     accurate when p is close to eps, and it is large when it is not (TOF/S close to pi / 4).
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static double LongWayNearSingularityGuess(double oneMs2tau, double tofbyS)
        {
            double q = Pow(4.0 * tofbyS / PI, 2.0 / 3.0);
            return oneMs2tau * q / (q - 1.0);
        }

        /// <summary>
        ///     The bottom of the multi-rev TOF curve (kBottom, TOF/S at kBottom), which separates the long-period (k > kBottom)
        ///     and short-period (k &lt; kBottom) branches.
        /// </summary>
        internal static (double kBottom, double tofbySBottom) MultiRevBottom(double tau, int nabs) =>
            MultiRevBottom(tau, nabs, RussellGuess.KBottom(tau, RussellGuess.X(tau), RussellGuess.Z(nabs), nabs), out _);

        /// <summary>
        ///     The limit of kBottom as N -> infinity (Russell 2022, Eq. 11).
        /// </summary>
        internal static double KBottomAsymptotic(double tau) => Abs(tau) < 1e-3 ? tau + 0.5 * tau * tau * tau : (1.0 - Sqrt(1.0 - 2.0 * tau * tau)) / tau;

        /// <summary>
        ///     The bottom of the multi-rev TOF curve, starting the iteration from kSeed, and the number of iterations taken.
        /// </summary>
        internal static (double kBottom, double tofbySBottom) MultiRevBottom(double tau, int nabs, double kSeed, out int iterations)
        {
            double tau2 = tau * tau;
            double tau3 = tau2 * tau;

            // Newton iteration on dT/dk = 0, safeguarded by bisection on the sign of dT/dk
            double lo = -SQRT2 + K_MARGIN;
            double hi = SQRT2 - K_MARGIN;
            double kBottom = Clamp(kSeed, lo, hi);
            double tofbySBottom = 0.0;
            iterations = 0;

            for (int i = 0; i < 100; i++)
            {
                iterations = i + 1;

                (double W0, double W1, double W2, double W3) = GetW(kBottom, nabs);
                double p = 1.0 - kBottom * tau;
                (double F0, double F1, double F2, _) = TofDerivs(p, tau, tau2, tau3, 0.0, 0.0, W0, W1, W2, W3, false);

                if (F1 > 0.0)
                    hi = kBottom;
                else
                    lo = kBottom;

                double kNext = F2 > 0.0 ? kBottom - F1 / F2 : 0.5 * (lo + hi);

                // After a Newton step this small the error is at roundoff, or the step is in the roundoff noise of dT/dk,
                // which is amplified close to k = +-sqrt(2).  The step may also be smaller than the resolution of k, so
                // this has to be checked before the bracket.  The minimum TOF/S is from the quadratic model of the
                // TOF/S curve at the last evaluation.
                if (F2 > 0.0 && Abs(kNext - kBottom) <= K_BOTTOM_STEP_TOL * Max(1.0, Abs(kBottom)))
                {
                    kBottom = Clamp(kNext, lo, hi);
                    tofbySBottom = F0 - 0.5 * F1 * F1 / F2;
                    break;
                }

                if (!(kNext > lo && kNext < hi))
                    kNext = 0.5 * (lo + hi);

                double dk = kNext - kBottom;
                kBottom = kNext;
                tofbySBottom = F0;

                // the bracket has collapsed
                if (Abs(dk) <= 4.0 * EPS * Max(1.0, Abs(kBottom)))
                    break;
            }

            return (kBottom, tofbySBottom);
        }
    }
}
